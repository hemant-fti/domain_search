func writeHeader(w io.Writer, result discovery.Result) {
	fmt.Fprintln(w)
	fmt.Fprintln(w, sectionLine)
	fmt.Fprintln(w, "  DOMAIN-SCOUT")
	fmt.Fprintln(w, "  Server Discovery Report")
	fmt.Fprintln(w, sectionLine)

	fmt.Fprintf(w, "  Status       : %s\n", scanStatusLabel(result.Status))

	if !result.ScannedAt.IsZero() {
		fmt.Fprintf(
			w,
			"  Scanned at   : %s\n",
			result.ScannedAt.Format("02 Jan 2006, 03:04:05 PM MST"),
		)
	}

	fmt.Fprintln(w)
}

