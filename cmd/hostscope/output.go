func writeServerInfo(w io.Writer, result discovery.Result) {
	fmt.Fprintln(w, "  01. SERVER OVERVIEW")
	fmt.Fprintln(w, separator)

	tw := newTableWriter(w)

	writeRow(tw, "Hostname", displayValue(result.Server.Hostname))
	writeRow(tw, "Operating system", displayValue(result.Server.OperatingSystem))
	writeRow(tw, "Kernel version", displayValue(result.Server.Kernel))
	writeRow(tw, "Server IP address", displayValue(result.Server.PrimaryIP))

	flushTable(tw)
	fmt.Fprintln(w)
}

// -----------------------------------------------------------------------------
// Detected services
// -----------------------------------------------------------------------------

func writeServices(w io.Writer, result discovery.Result) {
	fmt.Fprintln(w, "  02. DETECTED SERVICES")
	fmt.Fprintln(w, separator)

	if len(result.Servers) == 0 {
		fmt.Fprintln(w, "  No service details were found.")
		fmt.Fprintln(w)
		return
	}

	tw := newTableWriter(w)

	for _, service := range result.Servers {
		status := "NOT RUNNING"
		if service.Running {
			status = "RUNNING"
		}

		writeRow(
			tw,
			displayValue(service.Server),
			status,
		)
	}

	flushTable(tw)

	if len(result.DetectedServices) > 0 {
		fmt.Fprintf(
			w,
			"\n  Detected components: %s\n",
			displayList(result.DetectedServices),
		)
	}

	fmt.Fprintln(w)
}

// -----------------------------------------------------------------------------
// Discovered websites
// -----------------------------------------------------------------------------

func writeDomains(w io.Writer, result discovery.Result) {
	fmt.Fprintln(w, "  03. DISCOVERED WEBSITES")
	fmt.Fprintln(w, separator)

	if len(result.Domains) == 0 {
		fmt.Fprintln(w, "  No website configurations were discovered.")
		fmt.Fprintln(w)
		return
	}

	for index, domain := range result.Domains {
		fmt.Fprintf(
			w,
			"\n  Website %d: %s\n",
			index+1,
			displayValue(domain.Name),
		)

		tw := newTableWriter(w)

		writeRow(tw, "Web server", displayValue(domain.Source))
		writeRow(tw, "Configuration file", displayValue(domain.ConfigPath))
		writeRow(tw, "Website directory", displayValue(domain.DocumentRoot))
		writeRow(tw, "Proxy destination", displayValue(domain.ProxyTarget))
		writeRow(tw, "SSL certificate", displayValue(domain.SSLCertificate))
		writeRow(tw, "Aliases", displayList(domain.Aliases))
		writeRow(tw, "Listening ports", displayPorts(domain.Ports))

		flushTable(tw)
		fmt.Fprintln(w, separator)
	}

	fmt.Fprintln(w)
}

// -----------------------------------------------------------------------------
// System information
// -----------------------------------------------------------------------------

func writeSystemInfo(w io.Writer, result discovery.Result) {
	system := result.System

	fmt.Fprintln(w, "  04. SYSTEM INFORMATION")
	fmt.Fprintln(w, separator)

	tw := newTableWriter(w)

	writeRow(tw, "Hostname", displayValue(system.Hostname))
	writeRow(tw, "IPv4 addresses", displayList(system.IPv4))
	writeRow(tw, "IPv6 addresses", displayList(system.IPv6))
	writeRow(tw, "MAC address", displayValue(system.MAC))

	osName := strings.TrimSpace(
		displayValue(system.ServerOS) + " " + displayValue(system.OSVersion),
	)
	writeRow(tw, "Operating system", osName)

	writeRow(tw, "Architecture", displayValue(system.Architecture))
	writeRow(tw, "CPU model", displayValue(system.CPUModel))
	writeRow(tw, "CPU cores", formatCount(system.Cores))
	writeRow(tw, "CPU threads", formatCount(system.Threads))
	writeRow(tw, "Kernel version", displayValue(system.Kernel))
	writeRow(tw, "System uptime", formatUptime(system.Uptime))
	writeRow(tw, "Current user", displayValue(system.CurrentUser))
	writeRow(tw, "Time zone", displayValue(system.Timezone))

	flushTable(tw)

	fmt.Fprintln(w, "\n  DISK USAGE")

	disk := system.Disk
	diskTable := newTableWriter(w)

	writeRow(diskTable, "Root disk total", formatStorage(disk.TotalGB))
	writeRow(diskTable, "Disk used", formatStorage(disk.UsedGB))
	writeRow(diskTable, "Disk available", formatStorage(disk.FreeGB))

	flushTable(diskTable)

	fmt.Fprintln(w, "\n  MEMORY USAGE")

	memory := system.Memory
	memoryTable := newTableWriter(w)

	writeRow(memoryTable, "Total memory", formatStorage(memory.TotalGB))
	writeRow(memoryTable, "Used memory", formatStorage(memory.UsedGB))
	writeRow(memoryTable, "Available memory", formatStorage(memory.AvailableGB))
	writeRow(memoryTable, "Free memory", formatStorage(memory.FreeGB))

	flushTable(memoryTable)
	fmt.Fprintln(w)
}

