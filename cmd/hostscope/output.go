var (
	scanResultsFile = "scan-results.json"
	scanErrorsFile  = "scan-errors.json"
)

func writeJSONTo(output io.Writer, result any, pretty bool) error {
	data, err := marshalJSON(result, pretty)
	if err != nil {
		return fmt.Errorf("encode JSON: %w", err)
	}

	if err := saveScanResult(result); err != nil {
		return err
	}

	if _, err := output.Write(data); err != nil {
		return fmt.Errorf("write JSON output: %w", err)
	}

	return nil
}

func marshalJSON(result any, pretty bool) ([]byte, error) {
	var output bytes.Buffer
	encoder := json.NewEncoder(&output)
	encoder.SetEscapeHTML(false)

	if pretty {
		encoder.SetIndent("", "  ")
	}

	if err := encoder.Encode(result); err != nil {
		return nil, err
	}

	return output.Bytes(), nil
}

func appendJSONResult(path string, result []byte) (returnErr error) {
	result = bytes.TrimSpace(result)
	if !json.Valid(result) || len(result) == 0 || result[0] != '{' {
		return fmt.Errorf("append json result: record must be a valid JSON object")
	}

	file, err := os.OpenFile(
		path,
		os.O_APPEND|os.O_CREATE|os.O_RDWR,
		0644,
	)
	if err != nil {
		return fmt.Errorf("open results file: %w", err)
	}
	defer func() {
		if err := file.Close(); err != nil {
			returnErr = errors.Join(returnErr, fmt.Errorf("close results file: %w", err))
		}
	}()

	info, err := file.Stat()
	if err != nil {
		return fmt.Errorf("inspect results file: %w", err)
	}
	if info.Size() > 0 {
		var lastByte [1]byte
		if _, err := file.ReadAt(lastByte[:], info.Size()-1); err != nil {
			return fmt.Errorf("read end of results file: %w", err)
		}
		if lastByte[0] != '\n' {
			return fmt.Errorf("existing results file does not end with a newline")
		}
	}

	// Ensure every JSON object occupies exactly one line.
	result = append(result, '\n')

	if written, err := file.Write(result); err != nil {
		return fmt.Errorf("append json result: %w", err)
	} else if written != len(result) {
		return fmt.Errorf("append json result: %w", io.ErrShortWrite)
	}

	return nil
}

func writeHuman(output io.Writer, result discovery.Result) error {
	if err := saveScanResult(result); err != nil {
		return err
	}

	var report strings.Builder

	// Header.
	writeHeader(&report, result)

	// Summary.
	writeSummary(&report, result)

	// Server information.
	writeServerInfo(&report, result)

	// Detected services.
	writeServices(&report, result)

	// Discovered websites.
	writeDomains(&report, result)

	// System resources.
	writeSystemInfo(&report, result)

	// Warnings.
	writeWarnings(&report, result)

	fmt.Fprintln(&report)
	fmt.Fprintln(&report, sectionLine)
	fmt.Fprintln(&report, "  Scan report generated by DomainScout")
	fmt.Fprintln(&report, sectionLine)

	if _, err := io.WriteString(output, report.String()); err != nil {
		return fmt.Errorf("write human-readable output: %w", err)
	}

	return nil
}

