func writeWarnings(w io.Writer, result discovery.Result) {
	fmt.Fprintln(w, "  05. WARNINGS")
	fmt.Fprintln(w, separator)

	if len(result.Warnings) == 0 {
		fmt.Fprintln(w, "  No warnings. Everything completed without reported issues.")
		fmt.Fprintln(w)
		return
	}

	for index, warning := range result.Warnings {
		fmt.Fprintf(
			w,
			"  %d. %s\n",
			index+1,
			discovery.FriendlyErrorMessage(fmt.Errorf("%s", warning), ""),
		)
	}

	fmt.Fprintln(w)
}

// -----------------------------------------------------------------------------
// Formatting helpers
// -----------------------------------------------------------------------------

func newTableWriter(w io.Writer) *tabwriter.Writer {
	return tabwriter.NewWriter(w, 0, 4, 3, ' ', 0)
}

func writeRow(w io.Writer, label, value string) {
	fmt.Fprintf(w, "  %s\t: %s\n", label, value)
}

func flushTable(w *tabwriter.Writer) {
	_ = w.Flush()
}

func displayValue(value string) string {
	if strings.TrimSpace(value) == "" {
		return "Not reported"
	}

	return strings.TrimSpace(value)
}

func displayList(values []string) string {
	if len(values) == 0 {
		return "None reported"
	}

	return strings.Join(values, ", ")
}

func displayPorts(ports []int) string {
	if len(ports) == 0 {
		return "None reported"
	}

	values := make([]string, len(ports))
	for index, port := range ports {
		values[index] = strconv.Itoa(port)
	}

	return "[" + strings.Join(values, ", ") + "]"
}

func formatCount(value int) string {
	if value <= 0 {
		return "Not reported"
	}

	return strconv.Itoa(value)
}

func formatStorage(value float64) string {
	if value <= 0 {
		return "Not reported"
	}

	return fmt.Sprintf("%.2f GiB", value)
}

func formatUptime(seconds uint64) string {
	const (
		secondsPerDay  = 86400
		secondsPerHour = 3600
		secondsPerMin  = 60
	)

	days := seconds / secondsPerDay
	hours := seconds % secondsPerDay / secondsPerHour
	minutes := seconds % secondsPerHour / secondsPerMin

	var parts []string

	if days > 0 {
		parts = append(parts, countWithUnit(days, "day"))
	}

	if hours > 0 {
		parts = append(parts, countWithUnit(hours, "hour"))
	}

	if minutes > 0 {
		parts = append(parts, countWithUnit(minutes, "minute"))
	}

	if len(parts) == 0 {
		return "Less than a minute"
	}

	return strings.Join(parts, ", ")
}

func countWithUnit(count uint64, unit string) string {
	if count != 1 {
		unit += "s"
	}

	return fmt.Sprintf("%d %s", count, unit)
}

func scanStatusLabel(status string) string {
	switch strings.ToLower(status) {
	case "completed", "success", "successful":
		return "COMPLETED"
	case "completed_with_warnings":
		return "COMPLETED WITH WARNINGS"
	case "failed", "error":
		return "FAILED"
	default:
		return displayValue(status)
	}
}

func writeError(output io.Writer, code string, err error, jsonMode bool) error {
	if err == nil {
		return nil
	}

	event := discovery.NewScanError("error", "", err, time.Now().UTC())
	payload := struct {
		Error struct {
			Code    string `json:"code"`
			Message string `json:"message"`
		} `json:"error"`
	}{}

	payload.Error.Code = code
	payload.Error.Message = event.Message

	var outputErr error
	if jsonMode {
		if err := json.NewEncoder(output).Encode(payload); err != nil {
			outputErr = fmt.Errorf("write JSON error output: %w", err)
		}
	} else if _, err := fmt.Fprintln(output, event.Message); err != nil {
		outputErr = fmt.Errorf("write human-readable error output: %w", err)
	}

	logErr := appendJSONEvent(scanErrorsFile, event)
	return errors.Join(outputErr, logErr)
}

func saveScanResult(result any) error {
	data, err := marshalJSON(result, false)
	if err != nil {
		return fmt.Errorf("encode scan result: %w", err)
	}

	var record map[string]json.RawMessage
	if err := json.Unmarshal(data, &record); err != nil {
		return fmt.Errorf("prepare scan result record: %w", err)
	}

	delete(record, "warnings")
	delete(record, "error_events")

	recordType, err := json.Marshal("scan_result")
	if err != nil {
		return fmt.Errorf("encode scan result type: %w", err)
	}

	record["type"] = recordType
	data, err = json.Marshal(record)
	if err != nil {
		return fmt.Errorf("encode scan result record: %w", err)
	}

	// Save only the scan result.
	if err := appendJSONResult(scanResultsFile, data); err != nil {
		return fmt.Errorf("save scan result to %s: %w", scanResultsFile, err)
	}

	// Save warning/error events separately.
	if scan, ok := result.(discovery.Result); ok {
		events := scan.ErrorEvents
		if len(events) != len(scan.Warnings) {
			events = make([]discovery.ScanError, 0, len(scan.Warnings))

			for _, warning := range scan.Warnings {
				events = append(events, discovery.WarningEvent(warning))
			}
		}

		for _, event := range events {
			if err := appendJSONEvent(scanErrorsFile, event); err != nil {
				return fmt.Errorf(
					"save warning event to %s: %w",
					scanErrorsFile,
					err,
				)
			}
		}
	}

	return nil
}

func appendJSONEvent(path string, event discovery.ScanError) error {
	data, err := json.Marshal(event)
	if err != nil {
		return fmt.Errorf("encode %s event: %w", event.Type, err)
	}
	if err := appendJSONResult(path, data); err != nil {
		return fmt.Errorf("append %s event: %w", event.Type, err)
	}
	return nil
}

func saveFailedScanResult(scannedAt time.Time) error {
	return saveFailedScanResultTo(scanResultsFile, scannedAt)
}

func saveFailedScanResultTo(path string, scannedAt time.Time) error {
	if scannedAt.IsZero() {
		scannedAt = time.Now().UTC()
	}
	record := map[string]any{
		"type":       "scan_result",
		"status":     "failed",
		"scanned_at": scannedAt.UTC(),
	}
	data, err := json.Marshal(record)
	if err != nil {
		return fmt.Errorf("encode failed scan result: %w", err)
	}
	if err := appendJSONResult(path, data); err != nil {
		return fmt.Errorf("save failed scan result to %s: %w", path, err)
	}
	return nil
}

func requestsJSONOutput(args []string) bool {
	for _, arg := range args {
		switch arg {
		case "--json", "--compact", "--pretty":
			return true
		}
		switch {
		case strings.HasPrefix(arg, "--json="), strings.HasPrefix(arg, "--compact="):
			value, err := strconv.ParseBool(strings.SplitN(arg, "=", 2)[1])
			if err == nil && value {
				return true
			}
		case strings.HasPrefix(arg, "--pretty="):
			return true
		}
	}
	return false
}
