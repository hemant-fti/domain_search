// Summary
// -----------------------------------------------------------------------------

func writeSummary(w io.Writer, result discovery.Result) {
	total := len(result.Domains)
	if result.TotalDomains > total {
		total = result.TotalDomains
	}

	matched := 0
	mismatched := 0
	unresolved := 0

	for _, domain := range result.Domains {
		switch domain.DNS.Status {
		case "matches_server":
			matched++
		case "resolved_other_ip":
			mismatched++
		case "unresolved":
			unresolved++
		}
	}

	fmt.Fprintln(w, "  SCAN SUMMARY")
	fmt.Fprintln(w, separator)

	fmt.Fprintf(w, "  Websites discovered       : %d\n", total)
	fmt.Fprintf(w, "  DNS matches               : %d\n", matched)
	fmt.Fprintf(w, "  DNS points elsewhere      : %d\n", mismatched)
	fmt.Fprintf(w, "  DNS lookup unsuccessful   : %d\n", unresolved)

	fmt.Fprintln(w)
}

