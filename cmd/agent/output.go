const (
	sectionLine = "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
	separator   = "────────────────────────────────────────────────────────────"

	scanResultsFile = "scan-results.jsonl"
)

func writeJSON(result any, pretty bool) error {
	data, err := marshalJSON(result, pretty)
	if err != nil {
		return fmt.Errorf("encode JSON: %w", err)
	}

	if err := saveScanResult(result); err != nil {
		return err
	}

	if _, err := os.Stdout.Write(data); err != nil {
		return fmt.Errorf("write JSON output: %w", err)
	}

	return nil
}

func marshalJSON(result any, pretty bool) ([]byte, error) {
	var output bytes.Buffer
	encoder := json.NewEncoder(&output)
	encoder.SetEscapeHTML(false)

	if pretty {
		encoder.SetIndent("", "  ")
	}

	if err := encoder.Encode(result); err != nil {
		return nil, err
	}

	return output.Bytes(), nil
}

func appendJSONResult(path string, result []byte) error {
	file, err := os.OpenFile(
		path,
		os.O_APPEND|os.O_CREATE|os.O_WRONLY,
		0644,
	)
	if err != nil {
		return fmt.Errorf("open results file: %w", err)
	}
	defer file.Close()

	// Ensure every JSON object occupies exactly one line.
	result = bytes.TrimSpace(result)
	result = append(result, '\n')

	if _, err := file.Write(result); err != nil {
		return fmt.Errorf("append JSONL result: %w", err)
	}

	return nil
}

func writeHuman(output io.Writer, result discovery.Result) error {
	if err := saveScanResult(result); err != nil {
		return err
	}

	var report strings.Builder

	// Header.
	writeHeader(&report, result)

	// Summary.
	writeSummary(&report, result)

	// Server information.
	writeServerInfo(&report, result)

	// Detected services.
	writeServices(&report, result)

	// Discovered websites.
	writeDomains(&report, result)

	// System resources.
	writeSystemInfo(&report, result)

	// Warnings.
	writeWarnings(&report, result)

	fmt.Fprintln(&report)
	fmt.Fprintln(&report, sectionLine)
	fmt.Fprintln(&report, "  Scan report generated by DomainScout")
	fmt.Fprintln(&report, sectionLine)

	if _, err := io.WriteString(output, report.String()); err != nil {
		return fmt.Errorf("write human-readable output: %w", err)
	}

	return nil
}

// -----------------------------------------------------------------------------
// Header
// -----------------------------------------------------------------------------

func writeHeader(w io.Writer, result discovery.Result) {
	fmt.Fprintln(w)
	fmt.Fprintln(w, sectionLine)
	fmt.Fprintln(w, "  DOMAIN-SCOUT")
	fmt.Fprintln(w, "  Server Discovery Report")
	fmt.Fprintln(w, sectionLine)

	fmt.Fprintf(w, "  Status       : %s\n", scanStatusLabel(result.Status))

	if !result.ScannedAt.IsZero() {
		fmt.Fprintf(
			w,
			"  Scanned at   : %s\n",
			result.ScannedAt.Format("02 Jan 2006, 03:04:05 PM MST"),
		)
	}

	fmt.Fprintln(w)
}

// -----------------------------------------------------------------------------
// Summary
// -----------------------------------------------------------------------------

func writeSummary(w io.Writer, result discovery.Result) {
	total := len(result.Domains)
	if result.TotalDomains > total {
		total = result.TotalDomains
	}

	matched := 0
	mismatched := 0
	unresolved := 0

	for _, domain := range result.Domains {
		switch domain.DNS.Status {
		case "matches_server":
			matched++
		case "resolved_other_ip":
			mismatched++
		case "unresolved":
			unresolved++
		}
	}

	fmt.Fprintln(w, "  SCAN SUMMARY")
	fmt.Fprintln(w, separator)

	fmt.Fprintf(w, "  Websites discovered       : %d\n", total)
	fmt.Fprintf(w, "  DNS matches               : %d\n", matched)
	fmt.Fprintf(w, "  DNS points elsewhere      : %d\n", mismatched)
	fmt.Fprintf(w, "  DNS lookup unsuccessful   : %d\n", unresolved)

	fmt.Fprintln(w)
}

// -----------------------------------------------------------------------------
// Server information
// -----------------------------------------------------------------------------

func writeServerInfo(w io.Writer, result discovery.Result) {
	fmt.Fprintln(w, "  01. SERVER OVERVIEW")
	fmt.Fprintln(w, separator)

	tw := newTableWriter(w)

	writeRow(tw, "Hostname", displayValue(result.Server.Hostname))
	writeRow(tw, "Operating system", displayValue(result.Server.OperatingSystem))
	writeRow(tw, "Kernel version", displayValue(result.Server.Kernel))
	writeRow(tw, "Server IP address", displayValue(result.Server.PrimaryIP))

	flushTable(tw)
	fmt.Fprintln(w)
}

// -----------------------------------------------------------------------------
// Detected services
// -----------------------------------------------------------------------------

func writeServices(w io.Writer, result discovery.Result) {
	fmt.Fprintln(w, "  02. DETECTED SERVICES")
	fmt.Fprintln(w, separator)

	if len(result.Servers) == 0 {
		fmt.Fprintln(w, "  No service details were found.")
		fmt.Fprintln(w)
		return
	}

	tw := newTableWriter(w)

	for _, service := range result.Servers {
		status := "NOT RUNNING"
		if service.Running {
			status = "RUNNING"
		}

		writeRow(
			tw,
			displayValue(service.Server),
			status,
		)
	}

	flushTable(tw)

	if len(result.DetectedServices) > 0 {
		fmt.Fprintf(
			w,
			"\n  Detected components: %s\n",
			displayList(result.DetectedServices),
		)
	}

	fmt.Fprintln(w)
}

// -----------------------------------------------------------------------------
// Discovered websites
// -----------------------------------------------------------------------------

func writeDomains(w io.Writer, result discovery.Result) {
	fmt.Fprintln(w, "  03. DISCOVERED WEBSITES")
	fmt.Fprintln(w, separator)

	if len(result.Domains) == 0 {
		fmt.Fprintln(w, "  No website configurations were discovered.")
		fmt.Fprintln(w)
		return
	}

	for index, domain := range result.Domains {
		fmt.Fprintf(
			w,
			"\n  Website %d: %s\n",
			index+1,
			displayValue(domain.Name),
		)

		fmt.Fprintf(
			w,
			"  DNS status: %s\n",
			dnsStatusLabel(domain.DNS.Status),
		)

		tw := newTableWriter(w)

		writeRow(tw, "Web server", displayValue(domain.Source))
		writeRow(tw, "Configuration file", displayValue(domain.ConfigPath))
		writeRow(tw, "Website directory", displayValue(domain.DocumentRoot))
		writeRow(tw, "Proxy destination", displayValue(domain.ProxyTarget))
		writeRow(tw, "HTTPS / SSL", sslStatusLabel(domain.SSL))
		writeRow(tw, "Other domain names", displayList(domain.Aliases))
		writeRow(tw, "Listening ports", displayPorts(domain.Ports))
		writeRow(tw, "DNS addresses", displayList(domain.DNS.ResolvedIPs))

		switch domain.DNS.Status {
		case "matches_server":
			writeRow(tw, "Points to this server", "Yes")
		case "resolved_other_ip":
			writeRow(tw, "Points to this server", "No")
		default:
			writeRow(tw, "Points to this server", "Not verified")
		}

		flushTable(tw)
		fmt.Fprintln(w, separator)
	}

	fmt.Fprintln(w)
}

// -----------------------------------------------------------------------------
// System information
// -----------------------------------------------------------------------------

func writeSystemInfo(w io.Writer, result discovery.Result) {
	system := result.System

	fmt.Fprintln(w, "  04. SYSTEM INFORMATION")
	fmt.Fprintln(w, separator)

	tw := newTableWriter(w)

	writeRow(tw, "Hostname", displayValue(system.Hostname))
	writeRow(tw, "IPv4 addresses", displayList(system.IPv4))
	writeRow(tw, "IPv6 addresses", displayList(system.IPv6))
	writeRow(tw, "MAC address", displayValue(system.MAC))

	osName := strings.TrimSpace(
		displayValue(system.ServerOS) + " " + displayValue(system.OSVersion),
	)
	writeRow(tw, "Operating system", osName)

	writeRow(tw, "Architecture", displayValue(system.Architecture))
	writeRow(tw, "CPU model", displayValue(system.CPUModel))
	writeRow(tw, "CPU cores", formatCount(system.Cores))
	writeRow(tw, "CPU threads", formatCount(system.Threads))
	writeRow(tw, "Kernel version", displayValue(system.Kernel))
	writeRow(tw, "System uptime", formatUptime(system.Uptime))
	writeRow(tw, "Current user", displayValue(system.CurrentUser))
	writeRow(tw, "Time zone", displayValue(system.Timezone))

	flushTable(tw)

	fmt.Fprintln(w, "\n  DISK USAGE")

	disk := system.Disk
	diskTable := newTableWriter(w)

	writeRow(diskTable, "Root disk total", formatStorage(disk.TotalGB))
	writeRow(diskTable, "Disk used", formatStorage(disk.UsedGB))
	writeRow(diskTable, "Disk available", formatStorage(disk.FreeGB))

	flushTable(diskTable)

	fmt.Fprintln(w, "\n  MEMORY USAGE")

	memory := system.Memory
	memoryTable := newTableWriter(w)

	writeRow(memoryTable, "Total memory", formatStorage(memory.TotalGB))
	writeRow(memoryTable, "Used memory", formatStorage(memory.UsedGB))
	writeRow(memoryTable, "Available memory", formatStorage(memory.AvailableGB))
	writeRow(memoryTable, "Free memory", formatStorage(memory.FreeGB))

	flushTable(memoryTable)
	fmt.Fprintln(w)
}

// -----------------------------------------------------------------------------
// Warnings
// -----------------------------------------------------------------------------

func writeWarnings(w io.Writer, result discovery.Result) {
	fmt.Fprintln(w, "  05. WARNINGS")
	fmt.Fprintln(w, separator)

	if len(result.Warnings) == 0 {
		fmt.Fprintln(w, "  No warnings. Everything completed without reported issues.")
		fmt.Fprintln(w)
		return
	}

	for index, warning := range result.Warnings {
		fmt.Fprintf(w, "  %d. %s\n", index+1, warning)
	}

	fmt.Fprintln(w)
}

// -----------------------------------------------------------------------------
// Formatting helpers
// -----------------------------------------------------------------------------

func newTableWriter(w io.Writer) *tabwriter.Writer {
	return tabwriter.NewWriter(w, 0, 4, 3, ' ', 0)
}

func writeRow(w io.Writer, label, value string) {
	fmt.Fprintf(w, "  %s\t: %s\n", label, value)
}

func flushTable(w *tabwriter.Writer) {
	_ = w.Flush()
}

func displayValue(value string) string {
	if strings.TrimSpace(value) == "" {
		return "Not reported"
	}

	return strings.TrimSpace(value)
}

func displayList(values []string) string {
	if len(values) == 0 {
		return "None reported"
	}

	return strings.Join(values, ", ")
}

func displayPorts(ports []int) string {
	if len(ports) == 0 {
		return "None reported"
	}

	values := make([]string, len(ports))

	for index, port := range ports {
		values[index] = strconv.Itoa(port)
	}

	return strings.Join(values, ", ")
}

func formatCount(value int) string {
	if value <= 0 {
		return "Not reported"
	}

	return strconv.Itoa(value)
}

func formatStorage(value float64) string {
	if value <= 0 {
		return "Not reported"
	}

	return fmt.Sprintf("%.2f GiB", value)
}

func formatUptime(seconds uint64) string {
	const (
		secondsPerDay  = 86400
		secondsPerHour = 3600
		secondsPerMin  = 60
	)

	days := seconds / secondsPerDay
	hours := seconds % secondsPerDay / secondsPerHour
	minutes := seconds % secondsPerHour / secondsPerMin

	var parts []string

	if days > 0 {
		parts = append(parts, countWithUnit(days, "day"))
	}

	if hours > 0 {
		parts = append(parts, countWithUnit(hours, "hour"))
	}

	if minutes > 0 {
		parts = append(parts, countWithUnit(minutes, "minute"))
	}

	if len(parts) == 0 {
		return "Less than a minute"
	}

	return strings.Join(parts, ", ")
}

func countWithUnit(count uint64, unit string) string {
	if count != 1 {
		unit += "s"
	}

	return fmt.Sprintf("%d %s", count, unit)
}

func scanStatusLabel(status string) string {
	switch strings.ToLower(status) {
	case "completed", "success", "successful":
		return "COMPLETED"
	case "completed_with_warnings":
		return "COMPLETED WITH WARNINGS"
	case "failed", "error":
		return "FAILED"
	default:
		return displayValue(status)
	}
}

func dnsStatusLabel(status string) string {
	switch status {
	case "matches_server":
		return "[OK] DNS matches this server's IP"

	case "resolved_other_ip":
		return "[WARNING] DNS points to a different IP"

	case "unresolved":
		return "[WARNING] DNS lookup unsuccessful"

	default:
		return "[UNKNOWN] DNS status not available"
	}
}

func sslStatusLabel(enabled bool) string {
	if enabled {
		return "Enabled"
	}

	return "Not detected"
}

func writeError(output *os.File, code string, err error) {
	if err == nil {
		return
	}

	payload := struct {
		Error struct {
			Code    string `json:"code"`
			Message string `json:"message"`
		} `json:"error"`
	}{}

	payload.Error.Code = code
	payload.Error.Message = err.Error()

	_ = json.NewEncoder(output).Encode(payload)
}

func saveScanResult(result any) error {
	data, err := marshalJSON(result, false)
	if err != nil {
		return fmt.Errorf("encode scan result: %w", err)
	}

	if err := appendJSONResult(scanResultsFile, data); err != nil {
		return fmt.Errorf("save scan result to %s: %w", scanResultsFile, err)
	}

	return nil
}
